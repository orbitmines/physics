import math
import struct

KERNELS = r"""//! tick SNAP SWEEP SIGMA CREATE TOTAL MEET TOTAL POOLSUM CARRY SNAP SWEEP TOTAL

#define f32 float
#define u32 uint
#define i32 int
#define f32_of_u(x) ((float)(x))
#define i32_of_u(x) ((int)(x))
#define i32_of_f(x) ((int)(x))
#define u32_of_i(x) ((uint)(x))
#define absf(x) fabs(x)
#define maxf(a, b) fmax(a, b)
#define clampf(x, lo, hi) clamp(x, lo, hi)
#define rnd(x) round(x)
#define P (*Pp)

typedef struct { u32 cells; u32 A; u32 N; u32 K; f32 DEG; u32 holes; u32 tick; u32 pad; } Par;

u32 nA(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp, u32 a, u32 c) {
  return a * P.cells + c;
}

u32 wA(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp, u32 a, u32 c) {
  return P.cells * P.A + a * P.cells + c;
}

u32 dA(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp, u32 a, u32 c) {
  return 2u * P.cells * P.A + a * P.cells + c;
}

u32 fA(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp, u32 a, u32 c) {
  return 3u * P.cells * P.A + a * P.cells + c;
}

i32 hop(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp, u32 c, u32 a) {
  i32 x = i32_of_u(c % P.N);
  i32 y = i32_of_u(c / P.N);
  i32 tx = x + i32_of_f(dir[a].z);
  i32 ty = y + i32_of_f(dir[a].w);
  if (tx < 0 || ty < 0 || tx >= i32_of_u(P.N) || ty >= i32_of_u(P.N)) { return -1; }
  return ty * i32_of_u(P.N) + tx;
}

i32 back(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp, u32 c, u32 a) {
  i32 x = i32_of_u(c % P.N);
  i32 y = i32_of_u(c / P.N);
  i32 tx = x - i32_of_f(dir[a].z);
  i32 ty = y - i32_of_f(dir[a].w);
  if (tx < 0 || ty < 0 || tx >= i32_of_u(P.N) || ty >= i32_of_u(P.N)) { return -1; }
  return ty * i32_of_u(P.N) + tx;
}

u32 opp(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp, u32 a) {
  return (a + P.A / 2u) % P.A;
}

f32 facing(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp, u32 a, u32 b) {
  return (1.0 - (dir[a].x * dir[b].x + dir[a].y * dir[b].y)) / 2.0;
}

f32 toward(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp, u32 a, u32 c) {
  return (f32_of_u(P.A) * cel[0u * P.cells + c] - dir[a].x * cel[7u * P.cells + c] - dir[a].y * cel[8u * P.cells + c]) / f32_of_u(P.A);
}

f32 standing(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp, u32 a, u32 c) {
  f32 m = 0.0;
  if (cel[5u * P.cells + c] > 0.5) { m = st[dA(st, cel, dir, Pp, a, c)]; } else { m = st[wA(st, cel, dir, Pp, a, c)] + st[dA(st, cel, dir, Pp, a, c)]; }
  return maxf(0.0, m);
}

f32 land(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp, u32 a, u32 c, f32 w, f32 rays, f32 space, f32 folds) {
  st[dA(st, cel, dir, Pp, a, c)] = st[dA(st, cel, dir, Pp, a, c)] + w * rays / 4.0;
  f32 ev = w * P.DEG / f32_of_u(P.A) / 4.0;
  st[fA(st, cel, dir, Pp, a, c)] = maxf(0.0, st[fA(st, cel, dir, Pp, a, c)] + ev * folds);
  return ev * space;
}

f32 meet0_gate(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp, f32 rho, f32 nf) {
  f32 F = 1.0;
  f32 omega = 1.0;
  f32 beta = 0.0;
  f32 DEG = P.DEG;
  return clampf(F, 0.0, 1.0);
}

f32 meet0_rays(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp, f32 rho, f32 nf) {
  f32 F = 1.0;
  f32 omega = 1.0;
  f32 beta = 0.0;
  f32 DEG = P.DEG;
  return (-2.0);
}

f32 meet0_space(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp, f32 rho, f32 nf) {
  f32 F = 1.0;
  f32 omega = 1.0;
  f32 beta = 0.0;
  f32 DEG = P.DEG;
  return (-1.0);
}

f32 meet0_folds(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp, f32 rho, f32 nf) {
  f32 F = 1.0;
  f32 omega = 1.0;
  f32 beta = 0.0;
  f32 DEG = P.DEG;
  return 1.0;
}

//! kernel SNAP over cells*A
__kernel void SNAP(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp) {
  u32 i = (u32) get_global_id(0);
  if (i >= P.cells * P.A) { return; }
  st[P.cells * P.A + i] = st[i];
  st[2u * P.cells * P.A + i] = 0.0;
}

//! kernel SWEEP over cells
__kernel void SWEEP(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp) {
  u32 i = (u32) get_global_id(0);
  u32 c = i;
  if (i >= P.cells) { return; }
  f32 s = 0.0;
  f32 mx = 0.0;
  f32 my = 0.0;
  for (u32 a = 0u; a < P.A; a++) {
    f32 v = st[wA(st, cel, dir, Pp, a, c)];
    s = s + v;
    mx = mx + v * dir[a].x;
    my = my + v * dir[a].y;
  }
  cel[0u * P.cells + c] = s / f32_of_u(P.A);
  cel[7u * P.cells + c] = mx;
  cel[8u * P.cells + c] = my;
  cel[3u * P.cells + c] = 0.0;
}

//! kernel SIGMA over holes*A
__kernel void SIGMA(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp) {
  u32 i = (u32) get_global_id(0);
  if (i >= P.holes * P.A) { return; }
  u32 h = i / P.A;
  u32 a = i % P.A;
  f32 hx = dir[P.A + h].x;
  f32 hy = dir[P.A + h].y;
  f32 hz = dir[P.A + h].z;
  i32 cx = i32_of_f(rnd(hx + f32_of_u(P.K) * dir[a].x));
  i32 cy = i32_of_f(rnd(hy + f32_of_u(P.K) * dir[a].y));
  if (cx < 0 || cy < 0 || cx >= i32_of_u(P.N) || cy >= i32_of_u(P.N)) { return; }
  u32 c = u32_of_i(cy) * P.N + u32_of_i(cx);
  st[dA(st, cel, dir, Pp, a, c)] = st[dA(st, cel, dir, Pp, a, c)] + hz;
  st[fA(st, cel, dir, Pp, a, c)] = maxf(0.0, st[fA(st, cel, dir, Pp, a, c)] - hz / f32_of_u(P.A));
}

//! kernel CREATE over cells
__kernel void CREATE(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp) {
  u32 i = (u32) get_global_id(0);
  u32 c = i;
  if (i >= P.cells) { return; }
  if (cel[5u * P.cells + c] > 0.5) { return; }
  f32 rho = cel[0u * P.cells + c];
  f32 nf = cel[1u * P.cells + c];
  f32 F = 1.0;
  f32 omega = 1.0;
  f32 beta = 0.0;
  f32 DEG = P.DEG;
  f32 dSpace = 0.0;
  f32 fires0 = clampf((1.0 - pow(rho, DEG)), 0.0, 1.0) * 1.0;
  if (fires0 > 0.0) {
    for (u32 a = 0u; a < P.A; a++) {
      st[dA(st, cel, dir, Pp, a, c)] = st[dA(st, cel, dir, Pp, a, c)] + fires0 * (DEG) / DEG;
    }
    dSpace = dSpace + fires0 * (1.0);
    f32 df0 = fires0 * ((-DEG)) / f32_of_u(P.A);
    for (u32 a = 0u; a < P.A; a++) {
      st[fA(st, cel, dir, Pp, a, c)] = maxf(0.0, st[fA(st, cel, dir, Pp, a, c)] + df0);
    }
  }
  f32 fires1 = clampf((1.0 - omega), 0.0, 1.0) * rho;
  if (fires1 > 0.0) {
    for (u32 a = 0u; a < P.A; a++) {
      st[dA(st, cel, dir, Pp, a, c)] = st[dA(st, cel, dir, Pp, a, c)] + fires1 * (0.0) / DEG;
    }
    dSpace = dSpace + fires1 * (1.0);
    f32 df1 = fires1 * (0.0) / f32_of_u(P.A);
    for (u32 a = 0u; a < P.A; a++) {
      st[fA(st, cel, dir, Pp, a, c)] = maxf(0.0, st[fA(st, cel, dir, Pp, a, c)] + df1);
    }
  }
  cel[2u * P.cells + c] = cel[2u * P.cells + c] + dSpace;
}

//! kernel TOTAL over cells
__kernel void TOTAL(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp) {
  u32 i = (u32) get_global_id(0);
  u32 c = i;
  if (i >= P.cells) { return; }
  f32 nf = 0.0;
  for (u32 b = 0u; b < P.A; b++) {
    nf = nf + maxf(0.0, st[fA(st, cel, dir, Pp, b, c)]);
  }
  cel[1u * P.cells + c] = nf;
  cel[4u * P.cells + c] = 1.0 / (1.0 + nf);
}

//! kernel MEET over cells
__kernel void MEET(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp) {
  u32 i = (u32) get_global_id(0);
  u32 c = i;
  if (i >= P.cells) { return; }
  bool blocked = cel[5u * P.cells + c] > 0.5;
  f32 rho = cel[0u * P.cells + c];
  f32 nf = cel[1u * P.cells + c];
  f32 dSpace = 0.0;
  f32 gone = 0.0;
  for (u32 a = 0u; a < P.A; a++) {
    u32 o = opp(st, cel, dir, Pp, a);
    i32 to = hop(st, cel, dir, Pp, c, a);
    if (to >= 0 && !blocked) {
      f32 w = st[wA(st, cel, dir, Pp, a, c)] * toward(st, cel, dir, Pp, a, u32_of_i(to)) * meet0_gate(st, cel, dir, Pp, rho, nf);
      if (w > 0.0) {
        f32 ds = land(st, cel, dir, Pp, a, c, w, meet0_rays(st, cel, dir, Pp, rho, nf), meet0_space(st, cel, dir, Pp, rho, nf), meet0_folds(st, cel, dir, Pp, rho, nf));
        dSpace = dSpace + ds;
        gone = gone + absf(ds);
      }
    }
    i32 src = back(st, cel, dir, Pp, c, o);
    if (src >= 0) {
      u32 sc = u32_of_i(src);
      if (cel[5u * P.cells + sc] <= 0.5) {
        f32 r2 = cel[0u * P.cells + sc];
        f32 f2 = cel[1u * P.cells + sc];
        f32 w2 = st[wA(st, cel, dir, Pp, o, sc)] * toward(st, cel, dir, Pp, o, c) * meet0_gate(st, cel, dir, Pp, r2, f2);
        if (w2 > 0.0) {
          f32 ds2 = land(st, cel, dir, Pp, a, c, w2, meet0_rays(st, cel, dir, Pp, r2, f2), meet0_space(st, cel, dir, Pp, r2, f2), meet0_folds(st, cel, dir, Pp, r2, f2));
          dSpace = dSpace + ds2;
          gone = gone + absf(ds2);
        }
      }
    }
  }
  cel[2u * P.cells + c] = cel[2u * P.cells + c] + dSpace;
  cel[3u * P.cells + c] = gone;
}

//! kernel POOLSUM over cells
__kernel void POOLSUM(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp) {
  u32 i = (u32) get_global_id(0);
  u32 c = i;
  if (i >= P.cells) { return; }
  f32 keeps = cel[4u * P.cells + c];
  f32 p = 0.0;
  for (u32 a = 0u; a < P.A; a++) {
    f32 m = standing(st, cel, dir, Pp, a, c);
    if (m > 0.00000000000001) { p = p + m * (1.0 - keeps); }
  }
  cel[6u * P.cells + c] = p;
}

//! kernel CARRY over cells*A
__kernel void CARRY(__global f32* st, __global f32* cel, __global const float4* dir, __constant Par* Pp) {
  u32 i = (u32) get_global_id(0);
  if (i >= P.cells * P.A) { return; }
  u32 a = i / P.cells;
  u32 c = i % P.cells;
  f32 got = 0.0;
  i32 src = back(st, cel, dir, Pp, c, a);
  if (src >= 0) {
    u32 sc = u32_of_i(src);
    f32 m = standing(st, cel, dir, Pp, a, sc);
    if (m > 0.00000000000001) { got = got + m * cel[4u * P.cells + sc]; }
    f32 p = cel[6u * P.cells + sc];
    if (p > 0.0) {
      f32 nf = cel[1u * P.cells + sc];
      f32 part = 1.0 / f32_of_u(P.A);
      if (nf > 0.0) { part = st[fA(st, cel, dir, Pp, a, sc)] / nf; }
      got = got + p * part;
    }
  }
  st[nA(st, cel, dir, Pp, a, c)] = got;
}
"""

MAXH = 64
SLOTS = 9


def manifest(text):
    order, kernels, name, over = [], {}, None, None
    for line in text.split("\n"):
        if line.startswith("//! tick "):
            order = line[len("//! tick "):].split()
        elif line.startswith("//! kernel "):
            _, _, name, _, over = line.split()
            kernels[name] = over
    return order, kernels


def ready():
    try:
        import pyopencl as cl
        import numpy
        return any(p.get_devices() for p in cl.get_platforms())
    except Exception:
        return False


class CLField:
    def __init__(self, N, A=96, K=3):
        import pyopencl as cl
        import numpy as np
        self.np = np
        self.cl = cl
        self.N, self.K = N, K
        self.A = max(8, A & ~1)
        A = self.A
        self.cells = N * N
        cells = self.cells
        platform = next(p for p in cl.get_platforms() if p.get_devices())
        self.ctx = cl.Context(devices=platform.get_devices())
        self.queue = cl.CommandQueue(self.ctx)
        mf = cl.mem_flags
        self.st = cl.Buffer(self.ctx, mf.READ_WRITE, size=4 * cells * A * 4)
        self.cel = cl.Buffer(self.ctx, mf.READ_WRITE, size=SLOTS * cells * 4)
        self.dirb = cl.Buffer(self.ctx, mf.READ_WRITE, size=(A + MAXH) * 16)
        self.par = cl.Buffer(self.ctx, mf.READ_ONLY, size=32)
        zeros = np.zeros(4 * cells * A, dtype=np.float32)
        cl.enqueue_copy(self.queue, self.st, zeros)
        cl.enqueue_copy(self.queue, self.cel, np.zeros(SLOTS * cells, dtype=np.float32))
        self.order, self.over = manifest(KERNELS)
        self.program = cl.Program(self.ctx, KERNELS).build()
        self.ang = [2 * math.pi * a / A for a in range(A)]
        self.ux = [math.cos(x) for x in self.ang]
        self.uy = [math.sin(x) for x in self.ang]
        self.owed_x = [0.0] * A
        self.owed_y = [0.0] * A
        self.holes = []
        self.t = 0

    def add(self, h):
        self.holes.append(h)
        x, y = round(h.x), round(h.y)
        if 0 <= x < self.N and 0 <= y < self.N:
            self.cl.enqueue_copy(self.queue, self.cel, self.np.array([len(self.holes)], dtype=self.np.float32), dst_offset=(5 * self.cells + y * self.N + x) * 4)
        return h

    def _aim(self):
        A = self.A
        dirs = self.np.zeros((A + MAXH) * 4, dtype=self.np.float32)
        for a in range(A):
            self.owed_x[a] += self.K * self.ux[a]
            self.owed_y[a] += self.K * self.uy[a]
            sx, sy = round(self.owed_x[a]), round(self.owed_y[a])
            self.owed_x[a] -= sx
            self.owed_y[a] -= sy
            dirs[a * 4:a * 4 + 4] = [self.ux[a], self.uy[a], sx, sy]
        for i, h in enumerate(self.holes[:MAXH]):
            o = (A + i) * 4
            dirs[o:o + 4] = [round(h.x), round(h.y), min(1.0, (h.mx * h.ways) / max(1, h.ways)), getattr(h, "tag", 0) or 0]
        self.cl.enqueue_copy(self.queue, self.dirb, dirs)

    def _uniforms(self):
        data = self.np.frombuffer(struct.pack("IIIIfIII", self.cells, self.A, self.N, self.K, 8.0, min(len(self.holes), MAXH), self.t, 0), dtype=self.np.uint8)
        self.cl.enqueue_copy(self.queue, self.par, data)

    def _size(self, over):
        return {"cells": self.cells, "cells*A": self.cells * self.A, "holes*A": min(len(self.holes), MAXH) * self.A}[over]

    def tick(self):
        self._aim()
        self._uniforms()
        for name in self.order:
            n = self._size(self.over[name])
            if n == 0:
                continue
            kernel = getattr(self.program, name)
            kernel(self.queue, (-(-n // 64) * 64,), (64,), self.st, self.cel, self.dirb, self.par)
        self.queue.finish()
        self.t += 1

    def _read(self, buf, floats, offset=0):
        out = self.np.zeros(floats, dtype=self.np.float32)
        self.cl.enqueue_copy(self.queue, out, buf, src_offset=offset)
        self.queue.finish()
        return out

    def rho(self):
        return self._read(self.cel, self.cells, 0)

    def folds(self):
        return self._read(self.cel, self.cells, self.cells * 4)

    def gone(self):
        return self._read(self.cel, self.cells, 3 * self.cells * 4)

    def state(self):
        return self._read(self.st, self.cells * self.A)

    def mean(self):
        return float(self.rho().mean())


def gpu(N, A=96, K=3):
    return CLField(N, A, K)
