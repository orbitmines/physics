"""
orbitmines.physics - the continuous model on the GPU through wgpu-py (WebGPU, or Vulkan from GLSL).
GENERATED by `npx ray gen` from implementation/physics.ray and implementation/gen. Do not edit.

The kernels are Kernels.ray in the backend's shader language; this file is the runtime around them:
a device, the buffers, the passes of one tick as the text's manifest lists them, and the readback.
`gpu(N, A, K)` has the surface of the CPU Field: `tick()`, `state()`, `rho()`, `folds()`, `mean()`,
`add(hole)`. `ready()` says whether the binding is here.
"""
import math
import os
import struct
import sys

# wgpu probes every API it knows unless told which; the GL probe panics once an OpenGL context of
# another binding lives in the process (a test run over every backend), so name the platform's own
if "WGPU_BACKEND_TYPE" not in os.environ:
    os.environ["WGPU_BACKEND_TYPE"] = "Metal" if sys.platform == "darwin" else ("D3D12" if sys.platform == "win32" else "Vulkan")

KERNELS = r"""//! tick SNAP SWEEP SIGMA CREATE TOTAL MEET TOTAL POOLSUM CARRY SNAP SWEEP TOTAL

fn f32_of_u(x: u32) -> f32 { return f32(x); }
fn i32_of_u(x: u32) -> i32 { return i32(x); }
fn i32_of_f(x: f32) -> i32 { return i32(x); }
fn u32_of_i(x: i32) -> u32 { return u32(x); }
fn absf(x: f32) -> f32 { return abs(x); }
fn maxf(a: f32, b: f32) -> f32 { return max(a, b); }
fn clampf(x: f32, lo: f32, hi: f32) -> f32 { return clamp(x, lo, hi); }
fn rnd(x: f32) -> f32 { return round(x); }

struct Par { cells: u32, A: u32, N: u32, K: u32, DEG: f32, holes: u32, tick: u32, pad: u32 }
@group(0) @binding(0) var<uniform> P: Par;
@group(0) @binding(1) var<storage, read_write> st: array<f32>;
@group(0) @binding(2) var<storage, read_write> cel: array<f32>;
@group(0) @binding(3) var<storage, read> dir: array<vec4<f32>>;

fn nA(a: u32, c: u32) -> u32 {
  return a * P.cells + c;
}

fn wA(a: u32, c: u32) -> u32 {
  return P.cells * P.A + a * P.cells + c;
}

fn dA(a: u32, c: u32) -> u32 {
  return 2u * P.cells * P.A + a * P.cells + c;
}

fn fA(a: u32, c: u32) -> u32 {
  return 3u * P.cells * P.A + a * P.cells + c;
}

fn hop(c: u32, a: u32) -> i32 {
  let x: i32 = i32_of_u(c % P.N);
  let y: i32 = i32_of_u(c / P.N);
  let tx: i32 = x + i32_of_f(dir[a].z);
  let ty: i32 = y + i32_of_f(dir[a].w);
  if (tx < 0 || ty < 0 || tx >= i32_of_u(P.N) || ty >= i32_of_u(P.N)) { return -1; }
  return ty * i32_of_u(P.N) + tx;
}

fn back(c: u32, a: u32) -> i32 {
  let x: i32 = i32_of_u(c % P.N);
  let y: i32 = i32_of_u(c / P.N);
  let tx: i32 = x - i32_of_f(dir[a].z);
  let ty: i32 = y - i32_of_f(dir[a].w);
  if (tx < 0 || ty < 0 || tx >= i32_of_u(P.N) || ty >= i32_of_u(P.N)) { return -1; }
  return ty * i32_of_u(P.N) + tx;
}

fn opp(a: u32) -> u32 {
  return (a + P.A / 2u) % P.A;
}

fn facing(a: u32, b: u32) -> f32 {
  return (1.0 - (dir[a].x * dir[b].x + dir[a].y * dir[b].y)) / 2.0;
}

fn toward(a: u32, c: u32) -> f32 {
  var meet: f32 = 0.0;
  for (var b: u32 = 0u; b < P.A; b = b + 1u) {
    meet = meet + st[wA(b, c)] * facing(a, b);
  }
  return meet * 2.0 / f32_of_u(P.A);
}

fn standing(a: u32, c: u32) -> f32 {
  var m: f32 = 0.0;
  if (cel[5u * P.cells + c] > 0.5) { m = st[dA(a, c)]; } else { m = st[wA(a, c)] + st[dA(a, c)]; }
  return maxf(0.0, m);
}

fn land(a: u32, c: u32, w: f32, rays: f32, space: f32, folds: f32) -> f32 {
  st[dA(a, c)] = st[dA(a, c)] + w * rays / 4.0;
  let ev: f32 = w * P.DEG / f32_of_u(P.A) / 4.0;
  st[fA(a, c)] = maxf(0.0, st[fA(a, c)] + ev * folds);
  return ev * space;
}

fn meet0_gate(rho: f32, nf: f32) -> f32 {
  let F: f32 = 1.0;
  let omega: f32 = 1.0;
  let beta: f32 = 0.0;
  let DEG: f32 = P.DEG;
  return clampf(F, 0.0, 1.0);
}

fn meet0_rays(rho: f32, nf: f32) -> f32 {
  let F: f32 = 1.0;
  let omega: f32 = 1.0;
  let beta: f32 = 0.0;
  let DEG: f32 = P.DEG;
  return (-2.0);
}

fn meet0_space(rho: f32, nf: f32) -> f32 {
  let F: f32 = 1.0;
  let omega: f32 = 1.0;
  let beta: f32 = 0.0;
  let DEG: f32 = P.DEG;
  return (-1.0);
}

fn meet0_folds(rho: f32, nf: f32) -> f32 {
  let F: f32 = 1.0;
  let omega: f32 = 1.0;
  let beta: f32 = 0.0;
  let DEG: f32 = P.DEG;
  return 1.0;
}

//! kernel SNAP over cells*A
@compute @workgroup_size(64) fn SNAP(@builtin(global_invocation_id) gid: vec3<u32>) {
  let i: u32 = gid.y * 1024u * 64u + gid.x;
  if (i >= P.cells * P.A) { return; }
  st[P.cells * P.A + i] = st[i];
  st[2u * P.cells * P.A + i] = 0.0;
}

//! kernel SWEEP over cells
@compute @workgroup_size(64) fn SWEEP(@builtin(global_invocation_id) gid: vec3<u32>) {
  let i: u32 = gid.y * 1024u * 64u + gid.x;
  let c: u32 = i;
  if (i >= P.cells) { return; }
  var s: f32 = 0.0;
  for (var a: u32 = 0u; a < P.A; a = a + 1u) {
    s = s + st[wA(a, c)];
  }
  cel[0u * P.cells + c] = s / f32_of_u(P.A);
  cel[3u * P.cells + c] = 0.0;
}

//! kernel SIGMA over holes*A
@compute @workgroup_size(64) fn SIGMA(@builtin(global_invocation_id) gid: vec3<u32>) {
  let i: u32 = gid.y * 1024u * 64u + gid.x;
  if (i >= P.holes * P.A) { return; }
  let h: u32 = i / P.A;
  let a: u32 = i % P.A;
  let hx: f32 = dir[P.A + h].x;
  let hy: f32 = dir[P.A + h].y;
  let hz: f32 = dir[P.A + h].z;
  let cx: i32 = i32_of_f(rnd(hx + f32_of_u(P.K) * dir[a].x));
  let cy: i32 = i32_of_f(rnd(hy + f32_of_u(P.K) * dir[a].y));
  if (cx < 0 || cy < 0 || cx >= i32_of_u(P.N) || cy >= i32_of_u(P.N)) { return; }
  let c: u32 = u32_of_i(cy) * P.N + u32_of_i(cx);
  st[dA(a, c)] = st[dA(a, c)] + hz;
  st[fA(a, c)] = maxf(0.0, st[fA(a, c)] - hz / f32_of_u(P.A));
}

//! kernel CREATE over cells
@compute @workgroup_size(64) fn CREATE(@builtin(global_invocation_id) gid: vec3<u32>) {
  let i: u32 = gid.y * 1024u * 64u + gid.x;
  let c: u32 = i;
  if (i >= P.cells) { return; }
  if (cel[5u * P.cells + c] > 0.5) { return; }
  let rho: f32 = cel[0u * P.cells + c];
  let nf: f32 = cel[1u * P.cells + c];
  let F: f32 = 1.0;
  let omega: f32 = 1.0;
  let beta: f32 = 0.0;
  let DEG: f32 = P.DEG;
  var dSpace: f32 = 0.0;
  let fires0: f32 = clampf((1.0 - pow(rho, DEG)), 0.0, 1.0) * 1.0;
  if (fires0 > 0.0) {
    for (var a: u32 = 0u; a < P.A; a = a + 1u) {
      st[dA(a, c)] = st[dA(a, c)] + fires0 * (DEG) / DEG;
    }
    dSpace = dSpace + fires0 * (1.0);
    let df0: f32 = fires0 * ((-DEG)) / f32_of_u(P.A);
    for (var a: u32 = 0u; a < P.A; a = a + 1u) {
      st[fA(a, c)] = maxf(0.0, st[fA(a, c)] + df0);
    }
  }
  let fires1: f32 = clampf((1.0 - omega), 0.0, 1.0) * rho;
  if (fires1 > 0.0) {
    for (var a: u32 = 0u; a < P.A; a = a + 1u) {
      st[dA(a, c)] = st[dA(a, c)] + fires1 * (0.0) / DEG;
    }
    dSpace = dSpace + fires1 * (1.0);
    let df1: f32 = fires1 * (0.0) / f32_of_u(P.A);
    for (var a: u32 = 0u; a < P.A; a = a + 1u) {
      st[fA(a, c)] = maxf(0.0, st[fA(a, c)] + df1);
    }
  }
  cel[2u * P.cells + c] = cel[2u * P.cells + c] + dSpace;
}

//! kernel TOTAL over cells
@compute @workgroup_size(64) fn TOTAL(@builtin(global_invocation_id) gid: vec3<u32>) {
  let i: u32 = gid.y * 1024u * 64u + gid.x;
  let c: u32 = i;
  if (i >= P.cells) { return; }
  var nf: f32 = 0.0;
  for (var b: u32 = 0u; b < P.A; b = b + 1u) {
    nf = nf + maxf(0.0, st[fA(b, c)]);
  }
  cel[1u * P.cells + c] = nf;
  cel[4u * P.cells + c] = 1.0 / (1.0 + nf);
}

//! kernel MEET over cells
@compute @workgroup_size(64) fn MEET(@builtin(global_invocation_id) gid: vec3<u32>) {
  let i: u32 = gid.y * 1024u * 64u + gid.x;
  let c: u32 = i;
  if (i >= P.cells) { return; }
  let blocked: bool = cel[5u * P.cells + c] > 0.5;
  let rho: f32 = cel[0u * P.cells + c];
  let nf: f32 = cel[1u * P.cells + c];
  var dSpace: f32 = 0.0;
  var gone: f32 = 0.0;
  for (var a: u32 = 0u; a < P.A; a = a + 1u) {
    let o: u32 = opp(a);
    let to: i32 = hop(c, a);
    if (to >= 0 && !blocked) {
      let w: f32 = st[wA(a, c)] * toward(a, u32_of_i(to)) * meet0_gate(rho, nf);
      if (w > 0.0) {
        let ds: f32 = land(a, c, w, meet0_rays(rho, nf), meet0_space(rho, nf), meet0_folds(rho, nf));
        dSpace = dSpace + ds;
        gone = gone + absf(ds);
      }
    }
    let src: i32 = back(c, o);
    if (src >= 0) {
      let sc: u32 = u32_of_i(src);
      if (cel[5u * P.cells + sc] <= 0.5) {
        let r2: f32 = cel[0u * P.cells + sc];
        let f2: f32 = cel[1u * P.cells + sc];
        let w2: f32 = st[wA(o, sc)] * toward(o, c) * meet0_gate(r2, f2);
        if (w2 > 0.0) {
          let ds2: f32 = land(a, c, w2, meet0_rays(r2, f2), meet0_space(r2, f2), meet0_folds(r2, f2));
          dSpace = dSpace + ds2;
          gone = gone + absf(ds2);
        }
      }
    }
  }
  cel[2u * P.cells + c] = cel[2u * P.cells + c] + dSpace;
  cel[3u * P.cells + c] = gone;
}

//! kernel POOLSUM over cells
@compute @workgroup_size(64) fn POOLSUM(@builtin(global_invocation_id) gid: vec3<u32>) {
  let i: u32 = gid.y * 1024u * 64u + gid.x;
  let c: u32 = i;
  if (i >= P.cells) { return; }
  let keeps: f32 = cel[4u * P.cells + c];
  var p: f32 = 0.0;
  for (var a: u32 = 0u; a < P.A; a = a + 1u) {
    let m: f32 = standing(a, c);
    if (m > 0.00000000000001) { p = p + m * (1.0 - keeps); }
  }
  cel[6u * P.cells + c] = p;
}

//! kernel CARRY over cells*A
@compute @workgroup_size(64) fn CARRY(@builtin(global_invocation_id) gid: vec3<u32>) {
  let i: u32 = gid.y * 1024u * 64u + gid.x;
  if (i >= P.cells * P.A) { return; }
  let a: u32 = i / P.cells;
  let c: u32 = i % P.cells;
  var got: f32 = 0.0;
  let src: i32 = back(c, a);
  if (src >= 0) {
    let sc: u32 = u32_of_i(src);
    let m: f32 = standing(a, sc);
    if (m > 0.00000000000001) { got = got + m * cel[4u * P.cells + sc]; }
    let p: f32 = cel[6u * P.cells + sc];
    if (p > 0.0) {
      let nf: f32 = cel[1u * P.cells + sc];
      var part: f32 = 1.0 / f32_of_u(P.A);
      if (nf > 0.0) { part = st[fA(a, sc)] / nf; }
      got = got + p * part;
    }
  }
  st[nA(a, c)] = got;
}
"""

WIDE = 1024
MAXH = 64
SLOTS = 7


def manifest(text):
    """the pass order and the kernels of the text: (order, common, {name: (over, body)})"""
    order, common, kernels, name, over, body = [], [], {}, None, None, []
    for line in text.split("\n"):
        if line.startswith("//! tick "):
            order = line[len("//! tick "):].split()
        elif line.startswith("//! kernel "):
            if name is not None:
                kernels[name] = (over, "\n".join(body))
            _, _, name, _, over = line.split()
            body = []
        elif name is None:
            common.append(line)
        else:
            body.append(line)
    if name is not None:
        kernels[name] = (over, "\n".join(body))
    return order, "\n".join(common), kernels


def ready():
    try:
        import wgpu
        import numpy
        wgpu.gpu.request_adapter_sync(power_preference="high-performance")
        return True
    except Exception:
        return False


class GPUField:
    def __init__(self, N, A=96, K=3):
        import wgpu
        import numpy as np
        self.np = np
        self.N, self.K = N, K
        self.A = max(8, A & ~1)
        A = self.A
        self.cells = N * N
        cells = self.cells
        adapter = wgpu.gpu.request_adapter_sync(power_preference="high-performance")
        self.device = adapter.request_device_sync()
        d = self.device
        S = wgpu.BufferUsage.STORAGE | wgpu.BufferUsage.COPY_SRC | wgpu.BufferUsage.COPY_DST
        self.st = d.create_buffer(size=4 * cells * A * 4, usage=S)
        self.cel = d.create_buffer(size=SLOTS * cells * 4, usage=S)
        self.dirb = d.create_buffer(size=(A + MAXH) * 16, usage=S)
        self.par = d.create_buffer(size=32, usage=wgpu.BufferUsage.UNIFORM | wgpu.BufferUsage.COPY_DST)
        entries = [
            {"binding": 0, "visibility": wgpu.ShaderStage.COMPUTE, "buffer": {"type": wgpu.BufferBindingType.uniform}},
            {"binding": 1, "visibility": wgpu.ShaderStage.COMPUTE, "buffer": {"type": wgpu.BufferBindingType.storage}},
            {"binding": 2, "visibility": wgpu.ShaderStage.COMPUTE, "buffer": {"type": wgpu.BufferBindingType.storage}},
            {"binding": 3, "visibility": wgpu.ShaderStage.COMPUTE, "buffer": {"type": wgpu.BufferBindingType.read_only_storage}},
        ]
        layout = d.create_bind_group_layout(entries=entries)
        self.bind = d.create_bind_group(layout=layout, entries=[
            {"binding": 0, "resource": {"buffer": self.par, "offset": 0, "size": 32}},
            {"binding": 1, "resource": {"buffer": self.st, "offset": 0, "size": self.st.size}},
            {"binding": 2, "resource": {"buffer": self.cel, "offset": 0, "size": self.cel.size}},
            {"binding": 3, "resource": {"buffer": self.dirb, "offset": 0, "size": self.dirb.size}},
        ])
        pl = d.create_pipeline_layout(bind_group_layouts=[layout])
        self.order, common, kernels = manifest(KERNELS)
        self.pipes, self.over = {}, {}
        for name, (over, body) in kernels.items():
            module = d.create_shader_module(label="compute " + name, code=common + "\n" + body)
            self.pipes[name] = d.create_compute_pipeline(layout=pl, compute={"module": module, "entry_point": name if not common.startswith("#version") and "#version" not in common else "main"})
            self.over[name] = over
        self.ang = [2 * math.pi * a / A for a in range(A)]
        self.ux = [math.cos(x) for x in self.ang]
        self.uy = [math.sin(x) for x in self.ang]
        self.owed_x = [0.0] * A
        self.owed_y = [0.0] * A
        self.holes = []
        self.t = 0

    def add(self, h):
        self.holes.append(h)
        x, y = round(h.x), round(h.y)
        if 0 <= x < self.N and 0 <= y < self.N:
            self.device.queue.write_buffer(self.cel, (5 * self.cells + y * self.N + x) * 4, struct.pack("f", len(self.holes)))
        return h

    def _aim(self):
        A = self.A
        dirs = self.np.zeros((A + MAXH) * 4, dtype=self.np.float32)
        for a in range(A):
            self.owed_x[a] += self.K * self.ux[a]
            self.owed_y[a] += self.K * self.uy[a]
            sx, sy = round(self.owed_x[a]), round(self.owed_y[a])
            self.owed_x[a] -= sx
            self.owed_y[a] -= sy
            dirs[a * 4:a * 4 + 4] = [self.ux[a], self.uy[a], sx, sy]
        for i, h in enumerate(self.holes[:MAXH]):
            o = (A + i) * 4
            dirs[o:o + 4] = [round(h.x), round(h.y), min(1.0, (h.mx * h.ways) / max(1, h.ways)), getattr(h, "tag", 0) or 0]
        self.device.queue.write_buffer(self.dirb, 0, dirs.tobytes())

    def _uniforms(self):
        data = struct.pack("IIIIfIII", self.cells, self.A, self.N, self.K, 8.0, min(len(self.holes), MAXH), self.t, 0)
        self.device.queue.write_buffer(self.par, 0, data)

    def _size(self, over):
        return {"cells": self.cells, "cells*A": self.cells * self.A, "holes*A": min(len(self.holes), MAXH) * self.A}[over]

    def _run(self, enc, name):
        n = self._size(self.over[name])
        if n == 0:
            return
        p = enc.begin_compute_pass()
        p.set_pipeline(self.pipes[name])
        p.set_bind_group(0, self.bind)
        groups = -(-n // 64)
        p.dispatch_workgroups(min(groups, WIDE), -(-groups // WIDE), 1)
        p.end()

    def tick(self):
        self._aim()
        self._uniforms()
        enc = self.device.create_command_encoder()
        for name in self.order:
            self._run(enc, name)
        self.device.queue.submit([enc.finish()])
        self.t += 1

    def _read(self, buf, floats, offset=0):
        data = self.device.queue.read_buffer(buf, offset, floats * 4)
        return self.np.frombuffer(data, dtype=self.np.float32).copy()

    def rho(self):
        return self._read(self.cel, self.cells, 0)

    def folds(self):
        return self._read(self.cel, self.cells, self.cells * 4)

    def gone(self):
        return self._read(self.cel, self.cells, 3 * self.cells * 4)

    def state(self):
        return self._read(self.st, self.cells * self.A)

    def mean(self):
        return float(self.rho().mean())


def gpu(N, A=96, K=3):
    return GPUField(N, A, K)
