def _whole(x):
    """rounded away from nought, so that a heading and its opposite hop alike (Field.whole)"""
    x = round(x * 1000000) / 1000000
    return -int(math.floor(-x + 0.5)) if x < 0 else int(math.floor(x + 0.5))


class _Line:
    """the line as the source rules see it (Field.ray: Cell, Beam, Port stand on this): backed by this tick's readback and a list of what the rules did"""

    def __init__(self, field):
        self.f = field
        from . import Geometry, Vector
        A, K = field.A, field.K
        # the lattice's degree, and the DEG/A edges a heading of the line stands for (Field.edge)
        self.DEG = field.DEG
        self.edge = field.DEG / A
        # a step of one c-bar in whole cells, rounded away from nought (Field.whole), and the line's geometry as those hops in c-bar
        self.hx = [_whole(K * field.ux[a]) for a in range(A)]
        self.hy = [_whole(K * field.uy[a]) for a in range(A)]
        self.geometry = Geometry(name="line-" + str(A), offsets=[Vector(components=[self.hx[a] / K, self.hy[a] / K]) for a in range(A)])
        self.gathered = []
        # where each body's neighbours' folds sit in `gathered`: cell -> offset of its block of A
        self.around = {}
        self.entries = []

    def column_of(self, c):
        return c % self.f.N

    def row_of(self, c):
        return (c - c % self.f.N) // self.f.N

    def hop_from(self, c, d):
        return self.f._at(c % self.f.N + self.hx[d], (c - c % self.f.N) // self.f.N + self.hy[d])

    def blocks_at(self, c):
        return self.f.blocks[c]

    def source_at(self, c):
        return self.f.holes[int(self.f.blocks[c]) - 1] if self.f.blocks[c] > 0 else None

    def was_at(self, a, c):
        h = int(self.f.blocks[c]) - 1
        return float(self.gathered[h * self.f.A + a]) if 0 <= h < MAXH and len(self.gathered) > h * self.f.A + a else 0.0

    def folds_at(self, c):
        """the folds at a cell as the tick opened, per heading, as folds of the lattice's ways (Field.folds_at): a body's own cell, or a cell one step across any heading from one"""
        A = self.f.A
        nh = min(len(self.f.holes), MAXH)
        h = int(self.f.blocks[c]) - 1
        off = nh * A + h * A if 0 <= h < MAXH else self.around.get(c)
        if off is None:
            return [0.0] * A
        return [float(self.gathered[off + e]) * self.edge if len(self.gathered) > off + e else 0.0 for e in range(A)]

    def absorb(self, a, c, count):
        self.entries.extend([a * self.f.cells + c, -count, -1.0, 0.0])

    def light(self, a, c, count, tag):
        """a lit way of a point: the c-bar around the cell, K by K cells, each lit alike (Field.light)"""
        N, K = self.f.N, self.f.K
        x, y, half = c % N, (c - c % N) // N, (K - 1) // 2
        for dy in range(K):
            for dx in range(K):
                cell = self.f._at(x - half + dx, y - half + dy)
                if cell >= 0:
                    self.entries.extend([a * self.f.cells + cell, count, float(tag or 0), 1.0])


class GPUField:
    def __init__(self, N, A=96, K=3, tags=1, theory=None, DEG=8):
        self.DEG = DEG
        import wgpu
        import numpy as np
        self.np = np
        self.N, self.K = N, K
        self.A = max(8, A & ~1)
        A = self.A
        self.cells = N * N
        cells = self.cells
        self.tags = max(1, tags)
        planes = 10 + 2 * (self.tags - 1)
        SLOTS = 7 + self.tags
        self.slots = SLOTS
        adapter = wgpu.gpu.request_adapter_sync(power_preference="high-performance")
        try:
            lim = adapter.limits
            self.device = adapter.request_device_sync(required_limits={"max-storage-buffer-binding-size": lim["max-storage-buffer-binding-size"], "max-buffer-size": lim["max-buffer-size"]})
        except Exception:
            self.device = adapter.request_device_sync()
        d = self.device
        S = wgpu.BufferUsage.STORAGE | wgpu.BufferUsage.COPY_SRC | wgpu.BufferUsage.COPY_DST
        self.st = d.create_buffer(size=planes * cells * A * 4, usage=S)
        self.cel = d.create_buffer(size=SLOTS * cells * 4, usage=S)
        self.dirb = d.create_buffer(size=(A + MAXH + 10 * MAXH * A) * 16, usage=S)
        self.par = d.create_buffer(size=48, usage=wgpu.BufferUsage.UNIFORM | wgpu.BufferUsage.COPY_DST)
        entries = [
            {"binding": 0, "visibility": wgpu.ShaderStage.COMPUTE, "buffer": {"type": wgpu.BufferBindingType.uniform}},
            {"binding": 1, "visibility": wgpu.ShaderStage.COMPUTE, "buffer": {"type": wgpu.BufferBindingType.storage}},
            {"binding": 2, "visibility": wgpu.ShaderStage.COMPUTE, "buffer": {"type": wgpu.BufferBindingType.storage}},
            {"binding": 3, "visibility": wgpu.ShaderStage.COMPUTE, "buffer": {"type": wgpu.BufferBindingType.read_only_storage}},
        ]
        layout = d.create_bind_group_layout(entries=entries)
        self.bind = d.create_bind_group(layout=layout, entries=[
            {"binding": 0, "resource": {"buffer": self.par, "offset": 0, "size": 48}},
            {"binding": 1, "resource": {"buffer": self.st, "offset": 0, "size": self.st.size}},
            {"binding": 2, "resource": {"buffer": self.cel, "offset": 0, "size": self.cel.size}},
            {"binding": 3, "resource": {"buffer": self.dirb, "offset": 0, "size": self.dirb.size}},
        ])
        pl = d.create_pipeline_layout(bind_group_layouts=[layout])
        self.order, common, kernels = manifest(KERNELS)
        self.pipes, self.over = {}, {}
        for name, (over, body) in kernels.items():
            module = d.create_shader_module(label="compute " + name, code=common + "\n" + body)
            self.pipes[name] = d.create_compute_pipeline(layout=pl, compute={"module": module, "entry_point": name if not common.startswith("#version") and "#version" not in common else "main"})
            self.over[name] = over
        self.ang = [2 * math.pi * a / A for a in range(A)]
        self.ux = [math.cos(x) for x in self.ang]
        self.uy = [math.sin(x) for x in self.ang]
        self.owed_x = [0.0] * A
        self.owed_y = [0.0] * A
        self.holes = []
        self.t = 0
        self.blocks = [0.0] * cells
        if theory is None:
            from . import G as theory
        self.rules = theory.rules
        self.line = _Line(self)

    def _aim(self):
        A = self.A
        dirs = self.np.zeros((A + 2 * MAXH) * 4, dtype=self.np.float32)
        for a in range(A):
            dirs[a * 4:a * 4 + 4] = [self.ux[a], self.uy[a], self.K * self.ux[a], self.K * self.uy[a]]
        for i, h in enumerate(self.holes[:MAXH]):
            o = (A + i) * 4
            cell = h.cells[0] if h.cells else None
            dirs[o:o + 4] = [cell.index % self.N if cell else -1, (cell.index - cell.index % self.N) // self.N if cell else -1, 0.0, getattr(h, "tag", 0) or 0]
        self.device.queue.write_buffer(self.dirb, 0, dirs.tobytes())

    def _uniforms(self, z=0):
        data = struct.pack("IIIIfIIIIIII", self.cells, self.A, self.N, self.K, float(self.DEG), min(len(self.holes), MAXH), self.t, self.tags, z, min(len(self.line.entries) // 4, ENTRIES_MAX), 0, 0)
        self.device.queue.write_buffer(self.par, 0, data)

    def _size(self, over):
        return {"cells": self.cells, "cells*A": self.cells * self.A, "holes": min(len(self.holes), MAXH), "holes*A": min(len(self.holes), MAXH) * self.A, "entries": min(len(self.line.entries) // 4, ENTRIES_MAX), "one": 1 if self.line.entries else 0}[over]

    def _run(self, enc, name):
        n = self._size(self.over[name])
        if n == 0:
            return
        p = enc.begin_compute_pass()
        p.set_pipeline(self.pipes[name])
        p.set_bind_group(0, self.bind)
        groups = -(-n // 64)
        p.dispatch_workgroups(min(groups, WIDE), -(-groups // WIDE), 1)
        p.end()

    def _submit(self, names):
        for group in self._runs(names):
            for z in (range(self.tags - 1) if group[0].endswith("@z") else [0]):
                self._uniforms(z)
                enc = self.device.create_command_encoder()
                for name in group:
                    self._run(enc, name[:-2] if name.endswith("@z") else name)
                self.device.queue.submit([enc.finish()])

    def _write_block(self, c, v):
        self.device.queue.write_buffer(self.cel, (5 * self.cells + c) * 4, struct.pack("f", v))

    def _write_entries(self, arr):
        self.device.queue.write_buffer(self.dirb, (self.A + MAXH) * 16, arr.tobytes())

    def _at(self, x, y):
        return -1 if (x < 0 or y < 0 or x >= self.N or y >= self.N) else y * self.N + x

    def _block(self):
        """which cells the bodies stand on, off the bodies themselves - as Field.block"""
        now = [0.0] * self.cells
        for k, h in enumerate(self.holes):
            for cell in h.cells:
                now[cell.index] = float(k + 1)
        for c in range(self.cells):
            if self.blocks[c] != now[c]:
                self.blocks[c] = now[c]
                self._write_block(c, now[c])

    def _stages(self):
        """the passes of a tick, cut where the host steps in (`|`)"""
        out = [[]]
        for name in self.order:
            if name == "|":
                out.append([])
            else:
                out[-1].append(name)
        return out

    def add(self, h):
        from . import Bodies
        self.holes.append(h)
        Bodies.enter(self.line, h, self._at(round(h.x), round(h.y)))
        self._block()
        return h

    def tick(self):
        from . import Bodies
        self._aim()
        Bodies.begin(self.holes)
        stages = self._stages()
        self._submit(stages[0])
        nh = min(len(self.holes), MAXH)
        self.line.gathered = self._read(self.st, (2 + self.A) * nh * self.A, (9 + 2 * (self.tags - 1)) * self.cells * self.A * 4) if nh else []
        self.line.around = {}
        for k, h in enumerate(self.holes[:nh]):
            if h.cells:
                for a in range(self.A):
                    nc = self.line.hop_from(h.cells[0].index, a)
                    if nc >= 0:
                        self.line.around[nc] = 2 * nh * self.A + (k * self.A + a) * self.A
        self.line.entries = []
        Bodies.radiate(self.line, self.rules, self.holes)
        if self.line.entries:
            self._write_entries(self.np.array(self.line.entries[:ENTRIES_MAX * 4], dtype=self.np.float32))
        for stage in stages[1:]:
            self._submit(stage)
        Bodies.transport(self.line, self.rules, self.holes)
        self._block()
        self.t += 1

    def _runs(self, names):
        """passes in runs: a run of `NAME@z` passes goes once per tag, in order, each tag's before the next tag's"""
        out, run = [], []
        for name in names:
            if name.endswith("@z"):
                run.append(name)
            else:
                if run:
                    out.append(run)
                    run = []
                out.append([name])
        if run:
            out.append(run)
        return out

    def _read(self, buf, floats, offset=0):
        data = self.device.queue.read_buffer(buf, offset, floats * 4)
        return self.np.frombuffer(data, dtype=self.np.float32).copy()

    def rho(self):
        return self._read(self.cel, self.cells, 0)

    def folds(self):
        return self._read(self.cel, self.cells, self.cells * 4)

    def gone(self):
        return self._read(self.cel, self.cells, 3 * self.cells * 4)

    def arrived(self, z):
        return self._read(self.cel, self.cells, (7 + z) * self.cells * 4)

    def crossed(self):
        return self._read(self.cel, self.cells, 6 * self.cells * 4)

    def state(self):
        return self._read(self.st, self.cells * self.A)

    def mean(self):
        return float(self.rho().mean())


def gpu(N, A=96, K=3, tags=1, theory=None, DEG=8):
    return GPUField(N, A, K, tags, theory, DEG)
