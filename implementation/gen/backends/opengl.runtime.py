"""
orbitmines.physics - the continuous model on OpenGL compute shaders, through moderngl. GENERATED by
`npx ray gen` from implementation/physics.ray and implementation/gen. Do not edit.

The kernels are Kernels.ray in GLSL; this file is the runtime around them, with the surface of the
CPU Field: `tick()`, `state()`, `rho()`, `folds()`, `mean()`, `add(hole)`. `ready()` says whether the
binding and a 4.3 context are here.
"""
import math
import struct

KERNELS = r"""{kernels}"""

WIDE = 1024
MAXH = 64
SLOTS = 7


def manifest(text):
    order, common, kernels, name, over, body = [], [], {}, None, None, []
    for line in text.split("\n"):
        if line.startswith("//! tick "):
            order = line[len("//! tick "):].split()
        elif line.startswith("//! kernel "):
            if name is not None:
                kernels[name] = (over, "\n".join(body))
            _, _, name, _, over = line.split()
            body = []
        elif name is None:
            common.append(line)
        else:
            body.append(line)
    if name is not None:
        kernels[name] = (over, "\n".join(body))
    return order, "\n".join(common), kernels


def ready():
    try:
        import moderngl
        import numpy
        ctx = moderngl.create_standalone_context(require=430)
        ctx.release()
        return True
    except Exception:
        return False


class GLField:
    def __init__(self, N, A=96, K=3):
        import moderngl
        import numpy as np
        self.np = np
        self.N, self.K = N, K
        self.A = max(8, A & ~1)
        A = self.A
        self.cells = N * N
        cells = self.cells
        self.ctx = moderngl.create_standalone_context(require=430)
        c = self.ctx
        self.st = c.buffer(reserve=4 * cells * A * 4)
        self.cel = c.buffer(reserve=SLOTS * cells * 4)
        self.dirb = c.buffer(reserve=(A + MAXH) * 16)
        self.par = c.buffer(reserve=32)
        self.par.bind_to_uniform_block(0)
        self.st.bind_to_storage_buffer(1)
        self.cel.bind_to_storage_buffer(2)
        self.dirb.bind_to_storage_buffer(3)
        self.order, common, kernels = manifest(KERNELS)
        self.progs, self.over = {}, {}
        for name, (over, body) in kernels.items():
            self.progs[name] = c.compute_shader(common + "\n" + body)
            self.over[name] = over
        self.ang = [2 * math.pi * a / A for a in range(A)]
        self.ux = [math.cos(x) for x in self.ang]
        self.uy = [math.sin(x) for x in self.ang]
        self.owed_x = [0.0] * A
        self.owed_y = [0.0] * A
        self.holes = []
        self.t = 0

    def add(self, h):
        self.holes.append(h)
        x, y = round(h.x), round(h.y)
        if 0 <= x < self.N and 0 <= y < self.N:
            self.cel.write(struct.pack("f", len(self.holes)), offset=(5 * self.cells + y * self.N + x) * 4)
        return h

    def _aim(self):
        A = self.A
        dirs = self.np.zeros((A + MAXH) * 4, dtype=self.np.float32)
        for a in range(A):
            self.owed_x[a] += self.K * self.ux[a]
            self.owed_y[a] += self.K * self.uy[a]
            sx, sy = round(self.owed_x[a]), round(self.owed_y[a])
            self.owed_x[a] -= sx
            self.owed_y[a] -= sy
            dirs[a * 4:a * 4 + 4] = [self.ux[a], self.uy[a], sx, sy]
        for i, h in enumerate(self.holes[:MAXH]):
            o = (A + i) * 4
            dirs[o:o + 4] = [round(h.x), round(h.y), min(1.0, (h.mx * h.ways) / max(1, h.ways)), getattr(h, "tag", 0) or 0]
        self.dirb.write(dirs.tobytes())

    def _uniforms(self):
        self.par.write(struct.pack("IIIIfIII", self.cells, self.A, self.N, self.K, 8.0, min(len(self.holes), MAXH), self.t, 0))

    def _size(self, over):
        return {"cells": self.cells, "cells*A": self.cells * self.A, "holes*A": min(len(self.holes), MAXH) * self.A}[over]

    def tick(self):
        self._aim()
        self._uniforms()
        for name in self.order:
            n = self._size(self.over[name])
            if n == 0:
                continue
            groups = -(-n // 64)
            self.progs[name].run(min(groups, WIDE), -(-groups // WIDE), 1)
            self.ctx.memory_barrier()
        self.ctx.finish()
        self.t += 1

    def _read(self, buf, floats, offset=0):
        return self.np.frombuffer(buf.read(size=floats * 4, offset=offset), dtype=self.np.float32).copy()

    def rho(self):
        return self._read(self.cel, self.cells, 0)

    def folds(self):
        return self._read(self.cel, self.cells, self.cells * 4)

    def gone(self):
        return self._read(self.cel, self.cells, 3 * self.cells * 4)

    def state(self):
        return self._read(self.st, self.cells * self.A)

    def mean(self):
        return float(self.rho().mean())


def gpu(N, A=96, K=3):
    return GLField(N, A, K)
